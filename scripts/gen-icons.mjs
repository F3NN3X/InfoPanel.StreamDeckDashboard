// Bundles the lucide icon bodies (lucide-static) into src/render/lucide-data.ts: name -> inner SVG markup.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const dir = path.join(path.dirname(require.resolve("lucide-static/package.json")), "icons");
const icons = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
	const svg = readFileSync(path.join(dir, file), "utf8");
	const body = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"));
	icons[file.slice(0, -4)] = body.replace(/\s+/g, " ").replace(/> </g, "><").trim();
}
const out = path.join(import.meta.dirname, "..", "src", "render", "lucide-data.ts");
writeFileSync(out, `// Generated by scripts/gen-icons.mjs; do not edit.\nexport const LUCIDE: Record<string, string> = ${JSON.stringify(icons)};\n`);
console.log(`${Object.keys(icons).length} icons -> ${path.relative(process.cwd(), out)}`);
